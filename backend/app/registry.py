def format_penalty(rule: dict) -> str:
    """Короткая строка для отчёта: статья КоАП + штраф для юрлиц."""
    if not rule:
        return ""
    parts = [rule.get("koap") or ""]
    if rule.get("fine_legal"):
        parts.append(f"для юрлиц {rule['fine_legal']} ₽")
    if rule.get("fine_repeat"):
        parts.append(f"повторно {rule['fine_repeat']}")
    return ": ".join(p for p in parts[:2] if p) + (f"; {parts[2]}" if len(parts) > 2 else "")
