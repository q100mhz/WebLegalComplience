def build_documents(f: Facts) -> list[Doc]:
    docs = [privacy_policy(f), consent(f), checkbox_texts(f)]
    if f.has_newsletter:
        docs.append(newsletter_consent(f))
    if f.analytics or f.tracking_cookies:
        docs.append(cookie_banner(f))
    if f.has_recommendations:
        docs.append(recommendation_rules(f))
    return docs
