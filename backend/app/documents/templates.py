"""Шаблоны документов, заполняемые фактами проверки.

Документ — список блоков: ("h", текст), ("p", текст), ("ul", [пункты]), ("table", [заголовки], [[ячейки]]),
("code", текст), ("note", текст). Рендеринг в Markdown и DOCX — в render.py.
"""

from dataclasses import dataclass

from .facts import CATEGORY_RU, Facts

Block = tuple


@dataclass
class Doc:
    id: str
    title: str
    description: str
    blocks: list[Block]
    filename: str


def _intro_note(f: Facts) -> Block:
    return ("note", f"Черновик сформирован автоматически по результатам проверки сайта {f.host} от {f.checked_at}. "
                    "Заполните поля в квадратных скобках и согласуйте документ с юристом перед публикацией.")


def _processors(f: Facts) -> list[str]:
    """Сервисы, которым передаются данные (поручение обработки / предоставление)."""
    out = []
    for s in f.services:
        if s["category"] in ("analytics", "ads", "chat", "captcha", "maps", "video"):
            out.append(f"{s['name']} — {CATEGORY_RU.get(s['category'], s['category'])}"
                       + (" (иностранный сервис)" if s.get("foreign") else ""))
    out += [f"{p} — {CATEGORY_RU['payment']}" for p in f.payments]
    return out


