def howto(rule_id: str, platform: str | None) -> dict | None:
    """Шаги для платформы сайта; если для неё отдельной инструкции нет — общие шаги."""
    by_platform = HOWTO.get(rule_id)
    if not by_platform:
        return None
    if platform and platform in by_platform:
        return {"platform": platform, "steps": by_platform[platform]}
    steps = by_platform.get(ANY)
    return {"platform": None, "steps": steps} if steps else None
